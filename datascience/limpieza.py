def normalizar_caracteres_y_tildes(texto: str) -> str:
    """Corrige signos atípicos, comillas extrañas y normaliza espacio/tildes."""
    # Normalizar comillas, guiones y caracteres atípicos
    reemplazos_caracteres = {
        r"[“”«»]": '"',
        r"[‘’`´]": "'",
        r"–": "-",
        r"—": "-",
        r"\t": " ",
        r"\f": "",
        r"\v": "",
    }
    for patron, reemplazo in reemplazos_caracteres.items():
        texto = re.sub(patron, reemplazo, texto)

    return texto


def remover_boilerplate_regex(texto: str) -> str:
    """Filtra encabezados, pies de página, sellos leychile.cl, códigos N10948 y firmas."""
    if not texto or texto.startswith("[Error"):
        return ""

    # Remoción de marcas de agua y metadatos de leychile.cl / BCN
    texto = re.sub(
        r"Biblioteca del Congreso Nacional de Chile\s*-\s*www\.leychile\.cl\s*-\s*documento generado el.*?\n",
        "",
        texto,
        flags=re.IGNORECASE,
    )
    texto = re.sub(
        r"www\.leychile\.cl\s*;\s*codigo\s*:\s*[A-Z0-9]+",
        "",
        texto,
        flags=re.IGNORECASE,
    )
    texto = re.sub(
        r"leychile\.cl\s*/\s*N\d+", "", texto, flags=re.IGNORECASE
    )
    texto = re.sub(
        r"https?://www\.leychile\.cl/N\?\w+", "", texto, flags=re.IGNORECASE
    )
    texto = re.sub(r"\bN10948\b|\bN\d{5,}\b", "", texto)

    # B. Remoción de firmas electrónicas y sellos de validación
    texto = re.sub(
        r"Documento firmado electrónicamente de acuerdo a la Ley N°\s*\d+\.\d+.*?\n",
        "",
        texto,
        flags=re.IGNORECASE,
    )
    texto = re.sub(
        r"CVE\s*:\s*\d+|Código de Verificación:.*?\n",
        "",
        texto,
        flags=re.IGNORECASE,
    )

    # Remoción de encabezados/pies recurrentes (NCh, ISO, Copyright)
    texto = re.sub(
        r"capítulo \d+ de esta norma.*?\n", "", texto, flags=re.IGNORECASE
    )
    texto = re.sub(
        r"NORMA CHILENA OFICIAL.*?\n", "", texto, flags=re.IGNORECASE
    )
    texto = re.sub(
        r"ISO 14001:\d+ \(traducción oficial\)", "", texto, flags=re.IGNORECASE
    )
    texto = re.sub(
        r"DOCUMENTO PROTEGIDO POR COPYRIGHT.*?\n", "", texto, flags=re.IGNORECASE
    )
    texto = re.sub(r"página \d+ de \d+", "", texto, flags=re.IGNORECASE)

    # Limpieza de guiones de relleno e índices
    texto = re.sub(r"\.{3,}\s*\d+", "", texto)
    texto = re.sub(r"_{2,}", " ", texto)

    # Normalización de saltos y espacios
    texto = normalizar_caracteres_y_tildes(texto)
    texto = re.sub(r"[ \t]+", " ", texto)
    texto = re.sub(r"\n{3,}", "\n\n", texto)

    return texto.strip()


def unificar_terminos(texto: str) -> str:
    """Estandariza siglas y abreviaturas normativas."""
    reemplazos = {
        r"\bOAL\b": "Organismo Administrador de la Ley",
        r"\bSEREMI\b": "Secretaría Regional Ministerial",
        r"\bMINSAL\b": "Ministerio de Salud",
        r"\bISP\b": "Instituto de Salud Pública de Chile",
        r"\bS\.S\.O\.\b|\bSSO\b": "Seguridad y Salud Ocupacional",
        r"\bS\.S\.T\.\b|\bSST\b": "Seguridad y Salud en el Trabajo",
        r"\bArt\.\b|\bArt\b": "Artículo",
        r"\bDto\b\.?|\bDTO\b\.?": "Decreto",
        r"\bR\.M\.\b": "Resolución Ministerial",
        r"\bD\.S\.\b": "Decreto Supremo",
        r"\bRes\.\b|\bRES\.\b": "Resolución",
    }
    for patron, reemplazo in reemplazos.items():
        texto = re.sub(patron, reemplazo, texto, flags=re.IGNORECASE)
    return texto

