def procesar_carpeta_sso(
    ruta_carpeta_origen, ruta_carpeta_destino="./salida_markdown_limpio"
):
    print(
        f"[{datetime.now().strftime('%H:%M:%S')}] ⌨︎ Iniciando procesamiento y limpieza estricta..."
    )

    origen = Path(ruta_carpeta_origen)
    destino = Path(ruta_carpeta_destino)
    destino.mkdir(parents=True, exist_ok=True)

    extensiones = {".pdf", ".docx", ".txt", ".xlsx", ".xls"}
    archivos = [
        f
        for f in origen.rglob("*")
        if f.is_file() and f.suffix.lower() in extensiones
    ]

    procesados = 0
    for i, archivo in enumerate(archivos, 1):
        ext = archivo.suffix.lower()

        if ext == ".pdf":
            raw = leer_pdf(archivo)
        elif ext == ".docx":
            raw = leer_word(archivo)
        elif ext == ".txt":
            raw = leer_txt(archivo)
        elif ext in [".xlsx", ".xls"]:
            raw = leer_excel(archivo)
        else:
            continue

        # Limpieza de ruido Regex
        contenido_limpio = remover_boilerplate_regex(raw)

        if not contenido_limpio:
            contenido_final = (
                "*[Nota: Documento escaneado o sin texto digital extraíble]*"
            )
        else:
            # Unificación de términos
            contenido_unificado = unificar_terminos(contenido_limpio)
            # Formato Jerárquico en Markdown
            contenido_final = estructurar_jerarquia_markdown(contenido_unificado)

        nombre_md = f"{archivo.stem}.md"
        ruta_salida = destino / nombre_md

        # Frontmatter estándar en YAML
        yaml_frontmatter = f"""---
titulo: "{archivo.stem}"
extension_origen: "{ext}"
ruta_origen: "{archivo}"
fecha_procesamiento: "{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
---

# {archivo.stem}

{contenido_final}
"""

        with open(ruta_salida, "w", encoding="utf-8") as f:
            f.write(yaml_frontmatter)

        procesados += 1
        print(
            f"[{datetime.now().strftime('%H:%M:%S')}] ✅ [{i}/{len(archivos)}] Procesado: {nombre_md}"
        )

        if i % 15 == 0:
            gc.collect()

    print(
        f"\n✔ ¡Proceso completado! Archivos Markdown generados en '{destino}'"
    )

