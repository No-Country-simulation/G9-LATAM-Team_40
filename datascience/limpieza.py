# 3. ESTRUCTURACIÓN JERÁRQUICA EN MARKDOWN (SIN ALTERAR EL TEXTO ORIGINAL)
# ------------------------------------------------------------------------------


def estructurar_jerarquia_markdown(texto: str) -> str:
    """Aplica formato Markdown jerárquico (#, ##, ###) respetando el contenido intacto."""
    lineas = texto.split("\n")
    lineas_procesadas = []

    for linea in lineas:
        linea_str = linea.strip()
        if not linea_str:
            continue

        # Títulos de nivel 1 (TÍTULOS, LIBROS, CAPÍTULOS, ANEXOS)
        if re.match(
            r"^(ANEXO|TÍTULO|TITULO|LIBRO|CAPÍTULO|CAPITULO)\s+[A-Z0-9\.\-]+",
            linea_str,
            re.IGNORECASE,
        ):
            lineas_procesadas.append(f"\n## {linea_str}\n")
        # Títulos de nivel 2 (Numerales principales ej. 1. OBJETIVO, 2.1 ALCANCE)
        elif re.match(r"^\d{1,2}\.(\d{1,2})?\s+[A-ZÁÉÍÓÚÑ]{3,}", linea_str):
            lineas_procesadas.append(f"\n### {linea_str}\n")
        # Artículos (ej. Artículo 1.-)
        elif re.match(
            r"^(Artículo|Articulo)\s+\d+[\.\°\º\–\-]*",
            linea_str,
            re.IGNORECASE,
        ):
            lineas_procesadas.append(f"\n#### {linea_str}\n")
        else:
            lineas_procesadas.append(linea_str)

    return "\n".join(lineas_procesadas)

